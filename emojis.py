# Сортируем по длине символа по убыванию, чтобы многосимвольные
# последовательности (например "⚠️" = "⚠" + VS16) заменялись раньше
# своих более коротких префиксов.
_SORTED_CHARS = sorted(EMOJI_MAP.keys(), key=len, reverse=True)


def wrap_custom_emoji(text: str) -> str:
    """
    Оборачивает известные эмодзи в тексте в <tg-emoji emoji-id="...">.
    Не трогает уже вручную обёрнутые фрагменты <tg-emoji ...>...</tg-emoji> —
    это нужно для редких мест, где для одного и того же эмодзи-символа
    в разных сообщениях используется РАЗНЫЙ custom_emoji_id (например ⚡️
    в блоке "Наши преимущества" — свой ID, а не общий из EMOJI_MAP).
    """
    if not text:
        return text

    parts = _TG_EMOJI_TAG_RE.split(text)
    matches = _TG_EMOJI_TAG_RE.findall(text)

    result = []
    for i, part in enumerate(parts):
        for char in _SORTED_CHARS:
            if char in part:
                emoji_id = EMOJI_MAP[char]
                part = part.replace(char, f'<tg-emoji emoji-id="{emoji_id}">{char}</tg-emoji>')
        result.append(part)
        if i < len(matches):
            result.append(matches[i])  # уже готовый тег — как есть, без повторной обработки

    return "".join(result)


# ==================== КНОПКИ: иконка + цвет ====================

# callback_data -> style ("primary" синий / "success" зелёный / "danger" красный —
# только эти три значения поддерживает Bot API, "prestige" не существует).
BUTTON_STYLES = {
    "buy_subscription": "primary",
    "trial_subscription": "success",
    "about_service": "danger",
}


def style_and_iconify_button(button):
    """
    Мутирует InlineKeyboardButton на месте:
    - если текст начинается с известного эмодзи — переносит его в icon_custom_emoji_id
      (убирая дубликат из текста);
    - если callback_data кнопки есть в BUTTON_STYLES — красит кнопку.
    Кнопки "🔙 Назад" (даже если callback_data совпадает, напр. buy_subscription)
    не красим — это навигация, а не основной CTA.
    """
    text = getattr(button, "text", None)
    if text:
        for char in _SORTED_CHARS:
            prefix = f"{char} "
            if text.startswith(prefix):
                button.icon_custom_emoji_id = EMOJI_MAP[char]
                button.text = text[len(prefix):]
                break

    callback_data = getattr(button, "callback_data", None)
    is_back_button = bool(text) and text.startswith("🔙")
    if callback_data in BUTTON_STYLES and not is_back_button:
        button.style = BUTTON_STYLES[callback_data]